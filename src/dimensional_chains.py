def _coordinate_cells(coordinates: dict) -> tuple[str, str]:
    """Координаты и допуски элемента — в две ячейки таблицы."""
    place, tolerances = [], []
    for key, value in coordinates.items():
        if isinstance(value, dict) and "номинал" in value:
            axis = value.get("ось", key)
            place.append(f"{axis} {num(value['номинал'])}")
            if "допуск" in value:
                tolerances.append(f"±{num(value['допуск'])}")
        elif isinstance(value, dict) and "номиналы" in value:
            axis = value.get("ось", key)
            place.append(f"{axis} " + " и ".join(num(v) for v in value["номиналы"]))
            if "допуск" in value:
                tolerances.append(f"±{num(value['допуск'])}")
        elif isinstance(value, dict):
            place.append(f"{key.replace('_', ' ')}: " +
                         ", ".join(f"{name} {_plain(item)}" for name, item in value.items()))
        else:
            place.append(f"{key.replace('_', ' ')}: {_plain(value)}")
    return "; ".join(place), "; ".join(tolerances) if tolerances else "—"


def _plain(value) -> str:
    return num(value) if isinstance(value, (int, float)) else str(value)


def _spanning_line(link: dict) -> str:
    """Строка про замыкающее звено: справочное или с допуском."""
    if link["справочный"]:
        return f"{link['обозначение']} = {num(link['номинал'])} — справочный размер"
    return (f"{link['обозначение']} = {num(link['номинал'])} "
            f"{deviation(link['верхнее_отклонение'], link['нижнее_отклонение'])} "
            f"(допуск {num(link['допуск'])})")


def write(out_dir: Path = OUT_DIR) -> tuple[Path, Path]:
    """Собрать документ и JSON. Один запуск — оба файла с одними числами."""
    data = report()
    out_dir.mkdir(parents=True, exist_ok=True)
    doc = out_dir / DOC_NAME
    payload = out_dir / JSON_NAME
    doc.write_text(render_markdown(data), encoding="utf-8")
    payload.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                       encoding="utf-8")
    return doc, payload


