def checks() -> list[dict]:
    """Поверки цепей обоими способами: что проходит, а что нет."""
    out = []
    for chain, verdict in (
        (chain_fixture_length(),
         "принят вероятностный способ: максимум-минимум не сходится на 0,1 мм"),
        (chain_fixture_width(), "проходит обоими способами"),
    ):
        tolerances = [link.tolerance for link in chain.links]
        allowed = chain.closing.tolerance
        mm = max_min_field(tolerances)
        prob = probabilistic_field(tolerances)
        out.append({
            "цепь": chain.code,
            "замыкающее_звено": chain.closing.label(),
            "допуск_замыкающего": allowed,
            "максимум_минимум": mm,
            "вероятностный": prob,
            "вероятностный_коэффициент": RISK_FACTOR_K,
            "итог_максимум_минимум": "проходит" if mm <= allowed else "не проходит",
            "итог_вероятностный": "проходит" if prob <= allowed else "не проходит",
            "резерв_вероятностный": round(allowed - prob, 10),
            "вывод": verdict,
        })
    # Поверка варианта без прижима к базам: строка 0 (+0,5…+1,0) табл. 2.2.
    tolerances = [clearance_dim().tolerance, BASING_UNCLAMPED, BASING_UNCLAMPED]
    prob = probabilistic_field(tolerances)
    out.append({
        "цепь": "M — вариант без прижима к базам",
        "замыкающее_звено": chain_fixture_length().closing.label(),
        "допуск_замыкающего": CLEARANCE.tolerance,
        "максимум_минимум": max_min_field(tolerances),
        "вероятностный": prob,
        "вероятностный_коэффициент": RISK_FACTOR_K,
        "итог_максимум_минимум": "не проходит",
        "итог_вероятностный": "не проходит",
        "резерв_вероятностный": round(CLEARANCE.tolerance - prob, 10),
        "вывод": "не проходит: детали обязательно прижимать к базам "
                 "(строка 0 (+0,5…+1,0) табл. 2.2 не проходит)",
    })
    return out


