def num(value: float) -> str:
    """Число в русской записи: 10.5 → «10,5», 45.0 → «45»."""
    text = f"{value:,.4f}".replace(",", " ").rstrip("0").rstrip(".")
    return text.replace(".", ",")


def deviation(es: float, ei: float) -> str:
    """Отклонения в записи ЕСКД: +0,2/−0,8, ±0,5, −0,5."""
    if es == 0 and ei == 0:
        return "±0"
    if round(es, 10) == round(-ei, 10):
        return f"±{num(es)}"
    parts = []
    if es:
        parts.append(f"{'+' if es > 0 else '−'}{num(abs(es))}")
    if ei:
        parts.append(f"{'+' if ei > 0 else '−'}{num(abs(ei))}")
    return "/".join(parts)


def dimension_label(nominal: float, es: float, ei: float) -> str:
    return f"{num(nominal)} {deviation(es, ei)}"


def max_min_field(tolerances: list[float]) -> float:
    """Способ максимум-минимум: TΔ = ΣTi."""
    return round(sum(tolerances), 10)


def probabilistic_field(tolerances: list[float], k: float = RISK_FACTOR_K) -> float:
    """Вероятностный способ: TΔ = k·√(ΣTi²), округление до 0,01 мм."""
    return round(k * sum(t * t for t in tolerances) ** 0.5, 2)


def fixture_tolerance(item_tolerance: float) -> float:
    """Допуск приспособления: допуск изделия, жёстче в TIGHTENING_RATIO раза."""
    return round(item_tolerance / TIGHTENING_RATIO, 10)


