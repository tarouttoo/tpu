"""Расчёт размерных цепей приспособления для Направляющей 3865.00.10.

Источник чисел — этот модуль: документ и JSON собираются из тех же структур,
поэтому координаты и допуски не пересчитываются вручную, а воспроизводятся
командой `python src/dimensional_chains.py`.

Методика — лекция 03 «Точность, размерные цепи и расчёт допусков
приспособления» (`transcripts/лекции/03. …md`) и пособие Хайдаровой А. А.
«Сборочно-сварочные приспособления. Этапы проектирования», п. 2.3.3–2.3.6:

* замыкающее звено — размер, получаемый последним при сборке; зазор между
  Стойками — компенсирующее звено, единственный размер, которым управляют
  при сборке (§ 1 лекции 03);
* задача — прямая (проектная): по допуску исходного звена назначить допуски
  составляющих; правило — «допуск на базовые размеры приспособления в 2…3 раза
  (по пособию — в 0,5…3,0 раза) жёстче допуска на базовые размеры конструкции»
  (§ 6 лекции 03, п. 2.3.6 пособия);
* поверки — способ максимум-минимум (TΔ = ΣTi) и вероятностный
  (TΔ = k·√(ΣTi²), k = 1,0…1,3, риск брака 0,27 %) (§ 4 лекции 03);
* погрешности базирования — по табл. 2.2 пособия: 0 (+0,2…+0,5) при
  обработанных кромках упора и детали, 0 (+0,5…+1,0) при необработанной кромке
  детали, 0 (+1…+2) при обеих необработанных;
* размерная цепь приспособления MΔ = M3 + M1 + M2 (размер приспособления плюс
  погрешности базирования), связанная с цепью конструкции общим звеном
  (§ 6 лекции 03, рис. 2.30 пособия).

Система координат — изделия: X — длина (156), Y — ширина (90), Z — высота
(106); начало координат — центр изделия, Z = 0 — нижние торцы Стоек.

Идентификаторы модулей и констант (post.py, crossbar.py, POST_THICK, BAR_LEN)
повторяют имена файлов CAD-моделей; в текстах расчёта и в документах — только
Стойка и Перемычка (GLOSSARY.md).
"""

