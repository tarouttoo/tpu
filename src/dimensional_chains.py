@dataclass(frozen=True)
class Chain:
    code: str
    title: str
    kind: str                    # проверочная (обратная) / проектная (прямая) / производная
    method: str
    closing: Link                # замыкающее (или исходное) звено
    links: tuple[Link, ...]
    result: Link                 # замыкающее звено, полученное расчётом
    note: str

    def as_dict(self) -> dict:
        return {
            "цепь": self.code,
            "название": self.title,
            "вид": self.kind,
            "способ": self.method,
            "замыкающее_звено": self.closing.as_dict(),
            "составляющие_звенья": [link.as_dict() for link in self.links],
            "результат": self.result.as_dict(),
            "примечание": self.note,
        }


def _derive_closing(closing: Link, links: tuple[Link, ...], code: str, title: str) -> Link:
    """Обратная задача: замыкающее звено из составляющих (все увеличивающие)."""
    return Link(code, title, round(closing.nominal, 10),
                round(sum(link.es for link in links), 10),
                round(sum(link.ei for link in links), 10), "расчёт")


