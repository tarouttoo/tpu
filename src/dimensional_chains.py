@dataclass(frozen=True)
class Link:
    """Звено размерной цепи."""

    code: str           # обозначение: A1, A2, M3, B1 …
    title: str          # что это за размер
    nominal: float
    es: float           # верхнее отклонение, мм
    ei: float           # нижнее отклонение, мм
    source: str         # откуда взят допуск
    reference: bool = False   # справочный размер: допуск не назначается

    def __post_init__(self) -> None:
        if self.ei > self.es:
            raise ValueError(f"{self.code}: нижнее отклонение больше верхнего")
        if self.reference and (self.es or self.ei):
            raise ValueError(f"{self.code}: справочный размер не имеет допуска")

    @property
    def tolerance(self) -> float:
        return round(self.es - self.ei, 10)

    @property
    def max_size(self) -> float:
        return round(self.nominal + self.es, 10)

    @property
    def min_size(self) -> float:
        return round(self.nominal + self.ei, 10)

    def label(self) -> str:
        if self.reference:
            return f"{num(self.nominal)} (справочный)"
        return f"{num(self.nominal)} {deviation(self.es, self.ei)}"

    def as_dict(self) -> dict:
        return {
            "обозначение": self.code,
            "звено": self.title,
            "номинал": self.nominal,
            "справочный": self.reference,
            "верхнее_отклонение": self.es,
            "нижнее_отклонение": self.ei,
            "допуск": self.tolerance,
            "наибольший_размер": self.max_size,
            "наименьший_размер": self.min_size,
            "источник": self.source,
        }


