def chain_fixture_length() -> Chain:
    """Цепь M — размерная цепь приспособления: MΔ = M3 + M1 + M2 (§ 6 лекции 03).

    Замыкающее (исходное) звено — зазор 124 +0,5, заданный СБ; то же звено
    входит в цепь A (общее звено: A2 = MΔ), поэтому цепи A и M взаимно связаны.
    M3 — размер приспособления между внутренними упорами, M1 и M2 — погрешности
    базирования левой и правой Стойки.
    """
    spanning = Link("MΔ", "зазор между Стойками (задан сборочным чертежом)",
                    POST_CLEARANCE, +0.5, 0.0, SRC_SB)
    links = (clearance_dim(), BASING, BASING)
    return Chain(
        "M", "размерная цепь приспособления по длине (MΔ = M3 + M1 + M2)",
        "проектная (прямая)", "вероятностный", spanning, links,
        Link("MΔ", "зазор между Стойками, обеспечиваемый приспособлением",
             POST_CLEARANCE, probabilistic_field([link.tolerance for link in links]),
             0.0, "расчёт (вероятностный способ)"),
        "Общее звено с цепью A — зазор 124 +0,5, из-за него цепи A и M взаимно "
        "связаны (§ 6 лекции 03). Поле самого приспособления 0,2 мм жёстче поля "
        "изделия в 2,5 раза; поле собранного изделия шире — 0,42 мм, потому что "
        "в него входят ещё две погрешности базирования (MΔ = M3 + M1 + M2).",
    )


def chain_fixture_width() -> Chain:
    """Цепь M′ — та же цепь приспособления, но по ширине изделия.

    Замыкающее звено — ширина 90 −0,5; составляющие — размер приспособления
    от заднего упора до зажимов и погрешность базирования.
    """
    dim = width_dim()
    links = (dim, BASING)
    field = max_min_field([link.tolerance for link in links])
    return Chain(
        "M′", "размерная цепь приспособления по ширине", "проектная (прямая)",
        "максимум-минимум",
        Link("MΔ′", "ширина изделия (задана сборочным чертежом)",
             POST_WIDTH, 0.0, -WIDTH.tolerance, SRC_SB), links,
        Link("MΔ′", "ширина изделия, обеспечиваемая приспособлением",
             WIDTH.nominal, 0.0, -field, "расчёт (максимум-минимум)"),
        "Ширина детали может быть меньше номинала на 0,5 мм: этот запас "
        f"перекрывает ход винтовых зажимов. Поле {num(field)} мм (размер "
        f"приспособления {num(dim.tolerance)} + базирование {num(BASING.tolerance)}) "
        f"укладывается в поле изделия {num(WIDTH.tolerance)} мм.",
    )


def chain_crossbar() -> Chain:
    """Цепь Д (производная) — положение Перемычки над Стойками.

    Замыкающее звено — перекрытие Перемычки над Стойкой (площадка шва),
    справочный размер: он получается из размеров приспособления 135 и 124.
    """
    bar_stops = bar_stops_dim()
    inner_stops = clearance_dim()
    overlap = (BAR_LEN - POST_CLEARANCE) / 2
    overlap_tol = round((bar_stops.tolerance + inner_stops.tolerance) / 2, 10)
    return Chain(
        "Д", "производная цепь Перемычки: перекрытие над Стойкой",
        "производная", "полуразность: TΔ = (T₁ + T₂) / 2",
        Link("ДΔ", "перекрытие Перемычки над Стойкой (площадка шва, справочный)",
             overlap, +overlap_tol / 2, -overlap_tol / 2, "расчёт"),
        (bar_stops, inner_stops),
        Link("ДΔ", "перекрытие Перемычки над Стойкой (площадка шва)",
             overlap, +overlap_tol / 2, -overlap_tol / 2,
             "расчёт: (135 − 124) / 2"),
        "Перекрытие 5,5 мм — справочный размер: он получается из длины "
        "Перемычки и зазора между Стойками, на чертеже не нормируется. "
        "Именно оно определяет площадку углового шва.",
    )


def chains() -> tuple[Chain, ...]:
    return (chain_length(), chain_height(), chain_fixture_length(),
            chain_fixture_width(), chain_crossbar())


